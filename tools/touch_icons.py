"""Builds host/touch_icons.h: the touch buttons' pictures as 64x64 alpha masks.

The pictures are from game-icons.net (https://game-icons.net), CC BY 3.0, by
Lorc (https://lorcblog.blogspot.com) and Delapouite (https://delapouite.com);
host/about.h credits them. Each is its SVG's white path, rasterised here
(4x supersampled, even-odd fill).

    pip install pillow svg.path
    python tools/touch_icons.py            # fetches the SVGs from GitHub
"""
import os, re, sys, urllib.request
from PIL import Image, ImageDraw, ImageChops
from svg.path import parse_path, Move

SIZE = 64
# ICON_* name in host/window_sdl.c -> author/name in github.com/game-icons/icons
ICONS = [
    ('SWORD', 'lorc/broadsword'),
    ('DODGE', 'lorc/dodging'),
    ('SHEATHE', 'delapouite/scabbard'),
    ('GUARD', 'lorc/bordered-shield'),
    ('AIM', 'delapouite/crosshair'),
    ('TARGET', 'delapouite/convergence-target'),
    ('DEMON', 'delapouite/devil-mask'),
    ('SPIRIT', 'lorc/spinning-sword'),
    ('DANCE', 'lorc/spinning-blades'),
    ('FADE', 'lorc/back-forth'),
    ('CHARGE', 'lorc/hammer-drop'),
    ('RUN', 'lorc/run'),
]
URL = 'https://raw.githubusercontent.com/game-icons/icons/master/%s.svg'


def mask(src, size=SIZE, ss=4):
    big = size * ss
    out = Image.new('1', (big, big), 0)
    for attrs in re.findall(r'<path([^>]*)/>', src):
        if 'fill="#fff' not in attrs:
            continue                                   # the black square behind
        subs, cur = [], []
        for seg in parse_path(re.search(r'\bd="([^"]+)"', attrs).group(1)):
            if isinstance(seg, Move):
                if len(cur) > 2: subs.append(cur)
                cur = [seg.end]
                continue
            n = 1 if seg.__class__.__name__ in ('Line', 'Close') else max(4, int(seg.length() / 3))
            cur += [seg.point(i / n) for i in range(1, n + 1)]
        if len(cur) > 2: subs.append(cur)
        for s in subs:
            m = Image.new('1', (big, big), 0)
            ImageDraw.Draw(m).polygon([(z.real * big / 512, z.imag * big / 512) for z in s], fill=1)
            out = ImageChops.logical_xor(out, m)
    return out.convert('L').resize((size, size), Image.LANCZOS)


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = ['/* Generated by tools/touch_icons.py: do not edit. The touch buttons\'',
             ' * pictures, %dx%d alpha, from game-icons.net (CC BY 3.0) by Lorc and' % (SIZE, SIZE),
             ' * Delapouite. */',
             '#define TOUCH_ICON_SIZE %d' % SIZE,
             'static const struct { int icon; unsigned char a[%d]; } k_touch_icons[] = {' % (SIZE * SIZE)]
    for name, path in ICONS:
        src = urllib.request.urlopen(URL % path).read().decode('utf-8')
        data = mask(src).tobytes()
        lines.append('    { ICON_%s, {  /* %s */' % (name, path))
        for i in range(0, len(data), 32):
            lines.append('        ' + ','.join(str(b) for b in data[i:i + 32]) + ',')
        lines.append('    } },')
    lines.append('};')
    open(os.path.join(root, 'host', 'touch_icons.h'), 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('host/touch_icons.h: %d icons' % len(ICONS))


if __name__ == '__main__':
    main()
